namespace SteamFun.Services;

/// <summary>
/// Кураторский словарь пан-шуток для популярных игр (AppId + имя).
/// Тон: Fallout Shelter — коротко, конкретно под игру, без универсального «меню знает лучше».
/// </summary>
internal static class GameRoastCatalog
{
    public static bool TryRoast(
        int appId, string normalizedName, int minutes, Random rng,
        out string badge, out string joke)
    {
        badge = "";
        joke = "";

        foreach (var e in Entries)
        {
            if (e.AppIds.Contains(appId))
                return PickBand(e, minutes, rng, out badge, out joke);
        }

        foreach (var e in Entries)
        {
            if (e.Needles.Length == 0) continue;
            if (e.Needles.Any(n => normalizedName.Contains(n, StringComparison.Ordinal)))
                return PickBand(e, minutes, rng, out badge, out joke);
        }

        return false;
    }

    private static bool PickBand(Entry e, int minutes, Random rng, out string badge, out string joke)
    {
        var band = minutes <= 0 ? e.Zero
            : minutes < 180 ? e.Brief
            : minutes / 60.0 < 100 ? e.Mid
            : e.Heavy;

        badge = Pick(rng, band.Badges);
        joke = Pick(rng, band.Jokes);
        return true;
    }

    private static string Pick(Random rng, string[] options) =>
        options[rng.Next(options.Length)];

    private sealed record Band(string[] Badges, string[] Jokes);

    private sealed record Entry(int[] AppIds, string[] Needles, Band Zero, Band Brief, Band Mid, Band Heavy);

    private static Entry E(
        int[] ids, string[] needles,
        string[] zB, string[] zJ,
        string[] bB, string[] bJ,
        string[] mB, string[] mJ,
        string[] hB, string[] hJ) =>
        new(ids, needles, new Band(zB, zJ), new Band(bB, bJ), new Band(mB, mJ), new Band(hB, hJ));

